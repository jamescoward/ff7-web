#!/usr/bin/env node
// #168 (fourth budget, attempt 2): generate the Tier 2 probes that look for a
// choice window (field opcode ask) by routing to talkable models.
//
//   node runner/test/unit/choice-route-scenarios.js
//
// Writes harness/scenarios/save-boot-32*.json. Each probe loads a generated
// save, then chains route steps (runner/route.js, PR #282) to the talk range
// of each talkable model in turn, talks (Interact while facing the model) and
// presses on through every message. The route's `ask: 'note'` records the
// first window that waited in state 6 with its pointer enabled. Talkable
// models (TalkOff 0) per field: notes/168-choice-cursor.md, fresh budget
// attempt 2. Only numbers leave: per model, how the route ended (o<k>,
// ROUTE_OUTCOME; 0 not run), the triangles left on the path to the goal
// (r<k>; 1 in a goal triangle, 0 no path), the frames until a window opened
// (t<k>, 0 none) and the window that showed a choice (a<k>, index + 1; 0 none).
// Attempt 1 read t<k> = a<k> = 0 for all eight models, and the talk phase
// only runs when a route ends reached or stuck, so attempt 2 asks why: two
// models per probe with o<k> and r<k>. mds7st1's first goal is model 7, a
// control: #224 talked to it (a plain message), so a routed talk must open
// a window there if model goals and the talk phase work at all.
// Original project code, GPL-2.0-or-later.

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../../harness/scenarios');

/** Route limits per model: walk, stall patience, sidesteps, talk frames. */
export const ROUTE = Object.freeze({ timeout: 1800, patience: 90, detour: 6, talk: 600 });

/** The fields probed: save, field ID, and the talkable models routed to, in order. */
export const PROBES = Object.freeze([
  // mds7st1: 7 (#224's plain message) is the control; 5 is the nearest of the rest (third budget, attempt 2).
  { name: 'save-boot-32a-choice-route-mds7st1', save: 'disc1-mds7st1', field: 144, models: [7, 5] },
  { name: 'save-boot-32b-choice-route-nmkin1', save: 'disc1-nmkin-1', field: 120, models: [2, 3] },
]);

const MEMORY = {
  game_state: { addr: '0x8009c560', type: 'u16', description: 'g_GameState (s16 as u16; confirmed #76): field 1.' },
  map_cur: { addr: '0x8009a05c', type: 'u16', description: 'g_FieldCurrentMap (s16 as u16; confirmed #77): the field ID.' },
  loading: { addr: '0x800965e8', type: 'u16', description: 'g_IsFieldLoading (s16 as u16; confirmed #77): 2 in a settled field.' },
};

const LOAD = [
  { wait: { until: { mem: 'game_state', equals: 1 }, timeout: 3600, press: { buttons: ['circle'], every: 30, hold: 4 } } },
  // segments/field-loaded.json without its load_done metric (#77's rule: loading leaves 2, then reads 2 again).
  { wait: { until: { mem: 'game_state', equals: 1 }, timeout: 3600 } },
  { wait: { until: { mem: 'loading', differs: 2 }, timeout: 600 } },
  { wait: { until: { mem: 'loading', equals: 2 }, timeout: 3600 } },
  { wait: { frames: 30 } },
];

const routeTo = (k) => ({
  route: { to: { model: k }, ...ROUTE, ask: 'note', report: { outcome: `o${k}`, remain: `r${k}`, talk: `t${k}`, ask: `a${k}` } },
});

export const SCENARIOS = PROBES.map((p) => ({
  $schema: '../schema/scenario.schema.json',
  format: 2,
  tier: 2,
  name: p.name,
  description: `#168 fourth budget, attempt 2 (diagnostic; generated by runner/test/unit/choice-route-scenarios.js). Boot harness/saves/${p.save}.json (field ${p.field}) and load, wait 30 frames, then for each talkable model ${p.models.join(', ')} in turn: route over the walkmesh to its talk range (at most ${ROUTE.timeout} frames, patience ${ROUTE.patience}, up to ${ROUTE.detour} detours), face it and tap Interact until a message window opens (at most ${ROUTE.talk} frames), and press Interact through every waiting window until all are closed; ask 'note' records the first window seen waiting in state 6 with pointerEnabled 1 (a choice; pressing on picks the pointed option). Metrics per model k: o<k> (how the route ended: 1 reached, 2 stuck, 3 timeout, 4 left, 5 no mesh, 6 no goal, 7 no path; 0 not run), r<k> (triangles left on the path to the goal; 1 in a goal triangle, 0 no path), t<k> (frames until a window opened, 0 none) and a<k> (the choice window, index + 1, 0 none). Check: still in field ${p.field}. Only those numbers leave.`,
  boot: { disc: 1, save: p.save, slot: 1 },
  memory: MEMORY,
  input: [...LOAD, ...p.models.map(routeTo)],
  assert: [{ expect: { mem: 'map_cur', equals: p.field } }],
  metrics: p.models.flatMap((k) => [`o${k}`, `r${k}`, `t${k}`, `a${k}`]),
}));

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  for (const s of SCENARIOS) writeFileSync(path.join(OUT, `${s.name}.json`), `${JSON.stringify(s, null, 2)}\n`);
  console.log(`wrote ${SCENARIOS.length} scenarios`);
}
