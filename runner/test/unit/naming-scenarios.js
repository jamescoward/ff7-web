// The Tier 2 scenario of #289 ("Use default name" on Cloud's naming
// screen), generated so the press sequence is the semantic layer's own
// (NAMING_ACTIONS.useDefault in semantic/controls.js), not hand-written.
// naming.test.js checks the committed file equals this.
//
//   node runner/test/unit/naming-scenarios.js    rewrite the file
//
// It boots from touch-md1-1 (stretch 1's end, kept by touch-playthrough;
// the name sorts after it so Tier 2 runs it later) and routes to md1_1's
// gateway 1 with scene driving (#293). The route presses Interact through
// the gate scene's windows; on the naming screen it plays the sequence.
// The route reached md1_2 the same way in #120 budget 4 (PR #197,
// touch-s2s-gw-sc).
// Original project code, GPL-2.0-or-later.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ADDRESS_TABLE } from '../../../semantic/addresses.js';
import { NAMING_ACTIONS } from '../../../semantic/controls.js';
import { SCENARIO_DIR, serialise } from './planner-scenarios.js';

const hex = (n) => `0x${n.toString(16)}`;
const entry = (name) => {
  const e = ADDRESS_TABLE.entries.find((x) => x.name === name);
  if (!e) throw new Error(`no address entry ${name}`);
  return e;
};
const DECOMP = 'Xeeynamo/ff7-decomp@33ce78c (reference only, no code)';

export const NAME = 'touch-s2n-naming-confirm';
/** md1_2, the field past md1_1's gateway 1 (ff7-flat-wiki Field_ID; notes/120-touch-playthrough.md). */
export const MD1_2 = 0x76;
export const FIELD_MODE = 1;
export const NAME_ENTRY = 6;
/** Route limits as #120 budget 4's passing probe (touch-s2s-gw-sc). */
export const ROUTE = Object.freeze({ timeout: 9000, patience: 120, detour: 6, nudge: 300, scene: 3000 });

export function namingScenario() {
  const use = NAMING_ACTIONS.useDefault;
  const seq = use.sequence.map((g) => g.join(' + ')).join(', then ');
  return {
    $schema: '../schema/scenario.schema.json',
    format: 2,
    tier: 2,
    name: NAME,
    description: `#289 acceptance, generated by runner/test/unit/naming-scenarios.js. Boots from touch-md1-1 (kept by touch-playthrough). Input: wait 30 frames; route to md1_1's gateway 1 (md1_2), at most ${ROUTE.timeout} frames, driving scenes (#293): Interact through every waiting message window and, on the naming screen (gameState 5 with fieldEventCmd ${NAME_ENTRY}), semantic/controls.js NAMING_ACTIONS.useDefault (${seq}; each group held ${use.hold} frames, one every ${use.every}). End checks: md1_2 (0x76), field mode, and fieldEventCmd no longer ${NAME_ENTRY}. Metrics: out_g (route outcome: 1 reached, 2 stuck, 3 timeout, 4 left field mode, 5 no walkmesh, 6 no goal, 7 no path), named (route frame + 1 when the naming screen was first seen, 0 never), nleft (frames on the naming screen until field mode came back, 0 never), smode (first other gameState seen in a scene drive), evt (fieldEventCmd then), and the three end checks (1 holds, 0 not). Only those numbers leave.`,
    boot: { from: 'touch-md1-1' },
    memory: {
      map_cur: {
        addr: hex(entry('fieldId').address),
        type: 'u16',
        description: `fieldId: g_FieldCurrentMap (s16 as u16; confirmed #77): md1_1 0x75, md1_2 0x76. ${DECOMP} config/symbols.main.us.txt`,
      },
      game_state: {
        addr: hex(entry('gameState').address),
        type: 'u16',
        description: `gameState: g_GameState (s16 as u16; confirmed #76): field 1, menu 5. ${DECOMP} config/symbols.main.us.txt`,
      },
      event_cmd: {
        addr: hex(entry('fieldEventCmd').address),
        type: 'u8',
        description: `fieldEventCmd: g_FieldState.eventCmd (u8; #289 confirms 6, character name entry). ${DECOMP} include/game.h`,
      },
    },
    input: [
      { wait: { frames: 30 } },
      {
        route: {
          to: { gateway: 1 },
          ...ROUTE,
          naming: use.sequence.map((g) => [...g]),
          report: { outcome: 'out_g', named: 'named', nleft: 'nleft', smode: 'smode', evt: 'evt' },
        },
      },
    ],
    assert: [
      { expect: { mem: 'map_cur', equals: MD1_2 }, metric: 'md1_2' },
      { expect: { mem: 'game_state', equals: FIELD_MODE }, metric: 'field' },
      { expect: { mem: 'event_cmd', differs: NAME_ENTRY }, metric: 'evt_off' },
    ],
    metrics: ['out_g', 'named', 'nleft', 'smode', 'evt', 'md1_2', 'field', 'evt_off'],
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(SCENARIO_DIR, `${NAME}.json`), serialise(namingScenario()));
}
