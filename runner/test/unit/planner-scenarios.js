/**
 * A plan as format 2 steps, step for step what createPlanExecutor does: hold
 * the button for timing.hold frames, wait until the cursor reads the expected
 * row for at most timing.settle frames (a timeout fails the scenario: the
 * executor's stop), then hold nothing for timing.gap frames before the next
 * press. `metric` names the last wait.
 */
export function scriptFromPlan(plan, mem, metric) {
  const out = [];
  plan.steps.forEach((s, i) => {
    if (i > 0 && plan.timing.gap > 0) out.push({ wait: { frames: plan.timing.gap } });
    out.push({ buttons: [s.button], frames: plan.timing.hold });
    const w = { wait: { until: { mem, equals: s.expect }, timeout: plan.timing.settle } };
    if (metric && i === plan.steps.length - 1) w.metric = metric;
    out.push(w);
  });
  return out;
}

/** Presses with fixed waits, nothing checked: for the diagnostics, which must not stop early. */
function blindPresses(button, count, hold, after) {
  const out = [];
  for (let i = 0; i < count; i++) out.push({ buttons: [button], frames: hold }, { wait: { frames: after } });
  return out;
}

const main = menuPlanArgs('main');
/** The acceptance moves: rows 3, 0 and 7, one after another from the menu just open (row 0). */
export const ACCEPTANCE_MOVES = [[0, 3], [3, 0], [0, 7]];

/** Wrapped moves (the main menu wraps, #111 attempt 1): 0→9 is one Up, 9→2 three Downs through 0, 2→8 four Ups through 9. */
export const WRAP_MOVES = [[0, 9], [9, 2], [2, 8]];

/** A script running plans one after another, with the plan's gap between them. */
function chain(plans) {
  const input = [{ wait: { frames: 1 } }];
  plans.forEach((p, i) => {
    if (i > 0) input.push({ wait: { frames: p.timing.gap } });
    input.push(...scriptFromPlan(p, 'row0', `w_to${p.to}`));
  });
  input.push({ wait: { frames: 20 } });
  return input;
}

export function plannerScenarios() {
  // The acceptance scenario keeps the plans it had before wrapping was
  // confirmed (wraps: false), so its two Tier 2 runs ran the same script.
  const input = chain(ACCEPTANCE_MOVES.map(([from, to]) => planCursorMove({ from, to, ...main, wraps: false })));
  const wrapPlans = WRAP_MOVES.map(([from, to]) => planCursorMove({ from, to, ...main }));

  const accept = {
    $schema: '../schema/scenario.schema.json',
    format: 2,
    tier: 2,
    name: 'reactor-mode-2f-planner-rows',
    description: '#111: the menu planner. From menu-open (main-menu cursor on row 0), the script is semantic/planner.js output (generated by runner/test/unit/planner-scenarios.js; a Tier 1 test checks it): plans to row 3, then 0, then 7. Each press is followed by a wait until the cursor reads the planned next row (a timeout fails the scenario, as the executor stops). w_toN: frames the last wait of the plan to row N took. cursor_ok: the cursor reads 7 at the end. match: a rerun from the same snapshot. Only frame counts and 1/0 leave.',
    boot: { from: 'menu-open' },
    memory: MEMORY,
    input,
    assert: [
      { expect: { mem: 'row0', equals: 7 }, metric: 'cursor_ok' },
      { expect: { mem: 'game_state', equals: 5 }, metric: 'menu_ok' },
      { sameState: 'rerun', metric: 'match' },
    ],
    metrics: ['w_to3', 'w_to0', 'w_to7', 'cursor_ok', 'menu_ok', 'match', 'frames'],
  };

  const down = {
    $schema: '../schema/scenario.schema.json',
    format: 2,
    tier: 2,
    name: 'reactor-mode-2g-menu-rows-down',
    description: '#111: the main menu wraps past its last row. From menu-open (row 0): 11 Down presses (4 frames held, 16 free), with no checks between them; the cursor row (row0) then reads 1 (wrap_ok): 10 rows that wrap. (10 rows that stopped would read 9; 11 rows that stopped, 10.) Attempt 1 reported 1. menu_ok: still in the menu.',
    boot: { from: 'menu-open' },
    memory: MEMORY,
    input: [{ wait: { frames: 1 } }, ...blindPresses('down', 11, 4, 16), { wait: { frames: 20 } }],
    assert: [
      { expect: { mem: 'row0', equals: 1 }, metric: 'wrap_ok' },
      { expect: { mem: 'game_state', equals: 5 }, metric: 'menu_ok' },
    ],
    metrics: ['row0', 'wrap_ok', 'menu_ok', 'frames'],
  };

  const up = {
    $schema: '../schema/scenario.schema.json',
    format: 2,
    tier: 2,
    name: 'reactor-mode-2h-menu-up-from-top',
    description: '#111: the main menu wraps past its first row, to its last. From menu-open (row 0): one Up press (4 frames held); 36 frames later the cursor row (row0) reads 9 (wrap_ok): the last of 10 rows. (A cursor that stopped would read 0.) Attempt 1 reported 9. menu_ok: still in the menu.',
    boot: { from: 'menu-open' },
    memory: MEMORY,
    input: [{ wait: { frames: 1 } }, ...blindPresses('up', 1, 4, 16), { wait: { frames: 20 } }],
    assert: [
      { expect: { mem: 'row0', equals: 9 }, metric: 'wrap_ok' },
      { expect: { mem: 'game_state', equals: 5 }, metric: 'menu_ok' },
    ],
    metrics: ['row0', 'wrap_ok', 'menu_ok', 'frames'],
  };

  const wrap = {
    $schema: '../schema/scenario.schema.json',
    format: 2,
    tier: 2,
    name: 'reactor-mode-2i-planner-wrap',
    description: '#111: the menu planner with wrapping (the main menu wraps: 2g, 2h). From menu-open (row 0), the script is semantic/planner.js output with menuPlanArgs(\'main\') (generated by runner/test/unit/planner-scenarios.js): plans to row 9 (one Up), then 2 (Down through 0), then 8 (Up through 9). Each press is followed by a wait until the cursor reads the planned next row (a timeout fails the scenario). w_toN: frames the last wait of the plan to row N took. cursor_ok: the cursor reads 8 at the end. match: a rerun from the same snapshot. Only frame counts and 1/0 leave.',
    boot: { from: 'menu-open' },
    memory: MEMORY,
    input: chain(wrapPlans),
    assert: [
      { expect: { mem: 'row0', equals: 8 }, metric: 'cursor_ok' },
      { expect: { mem: 'game_state', equals: 5 }, metric: 'menu_ok' },
      { sameState: 'rerun', metric: 'match' },
    ],
    metrics: ['w_to9', 'w_to2', 'w_to8', 'cursor_ok', 'menu_ok', 'match', 'frames'],
  };
  return [accept, down, up, wrap];
}

export const serialise = (s) => `${JSON.stringify(s, null, 2)}\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const s of plannerScenarios()) writeFileSync(path.join(SCENARIO_DIR, `${s.name}.json`), serialise(s));
}
